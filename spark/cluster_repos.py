"""
spark/cluster_repos.py
----------------------
Spark job: load enriched commit data → aggregate repo-level features →
K-Means clustering → print cluster assignments.

Can run without HDFS using local JSONL files:
  python3 spark/cluster_repos.py

Or with HDFS:
  python3 spark/cluster_repos.py --hdfs hdfs://namenode:9000/user/hadoop/git-pattern

Output is also written to data/output/repo_clusters.json.

Dataset limitations
-------------------
The enriched dataset contains up to 50 recent commits per sampled repository,
NOT complete repository histories.  Cluster assignments should be interpreted
as patterns within this limited window, not as definitive measures of
repository health or developer behaviour over time.  The data labelled
'synthetic=True' was generated by the mock enrichment mode and does not
reflect real GitHub statistics.
"""

import argparse
import json
import os
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# PySpark imports — fail with a clear message if not installed
# ---------------------------------------------------------------------------
try:
    from pyspark.sql import SparkSession
    from pyspark.sql import functions as F
    from pyspark.ml.feature import VectorAssembler, StandardScaler
    from pyspark.ml.clustering import KMeans
    from pyspark.ml.evaluation import ClusteringEvaluator
    from pyspark.sql.types import (
        StructType, StructField, StringType, IntegerType,
        DoubleType, BooleanType, LongType,
    )
except ImportError:
    print(
        "[ERROR] pyspark is not installed.\n"
        "  pip3 install pyspark --break-system-packages",
        file=sys.stderr,
    )
    sys.exit(1)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

DEFAULT_K = 4           # number of clusters
DEFAULT_SEED = 42
FEATURE_COLS = [
    "commit_count",
    "avg_additions",
    "avg_deletions",
    "avg_lines_changed",
    "avg_files_changed",
    "merge_ratio",
]

OUTPUT_DIR = "data/output"
OUTPUT_FILE = "data/output/repo_clusters.json"

# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------

ENRICHED_SCHEMA = StructType([
    StructField("repo_id",            LongType(),    True),
    StructField("repo_name",          StringType(),  True),
    StructField("commit_sha",         StringType(),  True),
    StructField("author_identity",    StringType(),  True),
    StructField("author_timestamp",   StringType(),  True),
    StructField("committer_identity", StringType(),  True),
    StructField("committer_timestamp",StringType(),  True),
    StructField("commit_message",     StringType(),  True),
    StructField("parent_count",       IntegerType(), True),
    StructField("files_changed",      IntegerType(), True),
    StructField("additions",          IntegerType(), True),
    StructField("deletions",          IntegerType(), True),
    StructField("lines_changed",      IntegerType(), True),
    StructField("stats_available",    BooleanType(), True),
    StructField("files_available",    BooleanType(), True),
    StructField("synthetic",          BooleanType(), True),
])


# ---------------------------------------------------------------------------
# Feature aggregation
# ---------------------------------------------------------------------------

def aggregate_features(enriched_df):
    """Aggregate commit-level records to repo-level feature vectors."""
    return (
        enriched_df
        .withColumn("is_merge", F.when(F.col("parent_count") > 1, 1).otherwise(0))
        .groupBy("repo_name", "repo_id")
        .agg(
            F.count("commit_sha")          .alias("commit_count"),
            F.coalesce(F.sum("additions"), F.lit(0)).alias("total_additions"),
            F.coalesce(F.sum("deletions"), F.lit(0)).alias("total_deletions"),
            F.coalesce(F.sum("lines_changed"), F.lit(0)).alias("total_lines_changed"),
            F.coalesce(F.sum("files_changed"), F.lit(0)).alias("total_files_changed"),
            F.coalesce(F.sum("is_merge"), F.lit(0)).alias("merge_count"),
            F.coalesce(F.mean("additions"), F.lit(0.0)).alias("avg_additions"),
            F.coalesce(F.mean("deletions"), F.lit(0.0)).alias("avg_deletions"),
            F.coalesce(F.mean("lines_changed"), F.lit(0.0)).alias("avg_lines_changed"),
            F.coalesce(F.mean("files_changed"), F.lit(0.0)).alias("avg_files_changed"),
            F.countDistinct("author_identity").alias("distinct_authors"),
            F.coalesce(F.mean(F.col("parent_count").cast(DoubleType())), F.lit(0.0)).alias("avg_parent_count"),
        )
        .withColumn(
            "merge_ratio",
            F.when(F.col("commit_count") > 0, F.col("merge_count") / F.col("commit_count"))
            .otherwise(0.0)
            .cast(DoubleType()),
        )
    )


# ---------------------------------------------------------------------------
# Clustering
# ---------------------------------------------------------------------------

def run_kmeans(features_df, k: int, seed: int):
    """Assemble feature vector, scale, run KMeans."""
    if k < 2:
        raise ValueError(f"K-Means clustering requires k >= 2 (received k={k}).")

    assembler = VectorAssembler(
        inputCols=FEATURE_COLS,
        outputCol="raw_features",
        handleInvalid="skip",
    )
    assembled = assembler.transform(features_df)

    scaler = StandardScaler(
        inputCol="raw_features",
        outputCol="features",
        withStd=True,
        withMean=True,
    )
    scaler_model = scaler.fit(assembled)
    scaled = scaler_model.transform(assembled)

    kmeans = KMeans(k=k, seed=seed, featuresCol="features", predictionCol="cluster")
    model = kmeans.fit(scaled)
    predictions = model.transform(scaled)

    evaluator = ClusteringEvaluator(
        featuresCol="features", predictionCol="cluster", metricName="silhouette"
    )
    if k > 1 and predictions.select("cluster").distinct().count() > 1:
        silhouette = float(evaluator.evaluate(predictions))
    else:
        silhouette = 0.0

    return predictions, model, silhouette


# ---------------------------------------------------------------------------
# Output helpers
# ---------------------------------------------------------------------------

def print_results(results_df, silhouette: float) -> None:
    print("\n" + "=" * 72)
    print("Git Pattern Analysis — K-Means Clustering Results")
    print("=" * 72)
    print(
        f"  K = {results_df.select('cluster').distinct().count()} clusters | "
        f"Silhouette score = {silhouette:.4f}"
    )
    print()

    display_cols = [
        "cluster", "repo_name", "commit_count",
        "avg_additions", "avg_deletions", "avg_lines_changed",
        "avg_files_changed", "merge_ratio",
    ]

    rows = (
        results_df
        .select(*display_cols)
        .orderBy("cluster", "repo_name")
        .collect()
    )

    current_cluster = None
    for row in rows:
        if row.cluster != current_cluster:
            current_cluster = row.cluster
            print(f"  ── Cluster {current_cluster} ──────────────────────────────────────")
        print(
            f"  {row.repo_name:<45} "
            f"commits={row.commit_count:>4}  "
            f"avg_add={row.avg_additions:>8.1f}  "
            f"avg_del={row.avg_deletions:>7.1f}  "
            f"merge_ratio={row.merge_ratio:.2f}"
        )
    print()


def save_results(results_df, output_file: str) -> None:
    Path(output_file).parent.mkdir(parents=True, exist_ok=True)

    display_cols = [
        "cluster", "repo_name", "repo_id", "commit_count",
        "total_additions", "total_deletions", "total_lines_changed",
        "total_files_changed", "merge_count", "merge_ratio",
        "avg_additions", "avg_deletions", "avg_lines_changed",
        "avg_files_changed", "distinct_authors",
    ]

    rows = results_df.select(*display_cols).orderBy("cluster", "repo_name").collect()
    records = [row.asDict() for row in rows]

    with open(output_file, "w", encoding="utf-8") as fh:
        json.dump(records, fh, indent=2, default=str)

    print(f"  Results saved to: {output_file}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="K-Means clustering of GitHub repositories by commit patterns."
    )
    parser.add_argument(
        "--hdfs",
        default=None,
        metavar="HDFS_URL",
        help=(
            "HDFS base URL, e.g. hdfs://namenode:9000/user/hadoop/git-pattern. "
            "If omitted, reads local JSONL files."
        ),
    )
    parser.add_argument("--k", type=int, default=DEFAULT_K,
                        help=f"Number of clusters (default: {DEFAULT_K})")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED,
                        help=f"Random seed (default: {DEFAULT_SEED})")
    parser.add_argument("--output", default=OUTPUT_FILE,
                        help=f"Output file path (default: {OUTPUT_FILE})")
    args = parser.parse_args()

    spark = (
        SparkSession.builder
        .appName("GitPatternClustering")
        .master("local[*]")
        .config("spark.sql.shuffle.partitions", "4")
        .config("spark.driver.memory", "2g")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("WARN")

    # --- Load data ---
    if args.hdfs:
        enriched_path = f"{args.hdfs.rstrip('/')}/enriched_commits.jsonl"
        print(f"Loading from HDFS: {enriched_path}")
    else:
        enriched_path = "data/sample/enriched_commits.jsonl"
        print(f"Loading local file: {enriched_path}")

    enriched_df = spark.read.json(enriched_path, schema=ENRICHED_SCHEMA)
    total = enriched_df.count()
    print(f"Loaded {total} enriched commit records.")

    if total == 0:
        print("[ERROR] No enriched records found. Run enrichment first.", file=sys.stderr)
        sys.exit(1)

    # Warn if dataset is synthetic
    synthetic_count = enriched_df.filter(F.col("synthetic") == True).count()
    if synthetic_count > 0:
        print(
            f"  [NOTE] {synthetic_count}/{total} records are synthetic (mock mode). "
            "Cluster assignments are for pipeline demonstration only."
        )

    # --- Aggregate features ---
    features_df = aggregate_features(enriched_df)
    repo_count = features_df.count()
    print(f"Aggregated features for {repo_count} repositories.")

    if repo_count < 2:
        print(
            f"[ERROR] At least 2 repositories required for K-Means clustering (found {repo_count}).",
            file=sys.stderr,
        )
        sys.exit(1)

    if repo_count < args.k:
        print(
            f"[WARNING] Fewer repositories ({repo_count}) than clusters ({args.k}). "
            f"Reducing k to {repo_count}.",
            file=sys.stderr,
        )
        args.k = repo_count

    # --- Cluster ---
    print(f"\nRunning K-Means with k={args.k}, seed={args.seed} …")
    predictions, model, silhouette = run_kmeans(features_df, args.k, args.seed)

    # --- Output ---
    print_results(predictions, silhouette)
    save_results(predictions, args.output)

    spark.stop()


if __name__ == "__main__":
    main()
